#!/usr/bin/env python3
"""Rebuild js/catalogue_data.js from data/catalogue.json (the app reads the .js file; people edit the .json).

    python scripts/build_catalogue.py          # rebuild
    python scripts/build_catalogue.py --check  # exit 1 if the .js is out of date (used by CI and tests)

It also checks that each row's short requirement text ("E60 M60 PS60") matches its full subjects list, so a typo
in one can never silently change what a learner sees.
"""
import json, os, re, sys, hashlib
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mz_common as C

SUBJECT_CODES = {"E": ["English Home Language", "English First Additional Language"], "M": ["Mathematics"], "ML": ["Mathematical Literacy"],
                 "MML": ["Mathematics", "Mathematical Literacy"], "PS": ["Physical Sciences"], "LS": ["Life Sciences"], "ACC": ["Accounting"],
                 "BUS": ["Business Studies"], "ECO": ["Economics"], "GEO": ["Geography"], "HIS": ["History"], "IT": ["Information Technology"],
                 "CAT": ["Computer Applications Technology"], "EGD": ["Engineering Graphics and Design"], "TOU": ["Tourism"],
                 "AGR": ["Agricultural Sciences"], "CON": ["Consumer Studies"]}
OUT = os.path.join(C.ROOT, 'js', 'catalogue_data.js')
HEADER = '/* Generated by scripts/build_catalogue.py - do not edit by hand. */\n'


def build():
    cat = C.load(C.path('catalogue.json'))
    insts = []
    for i in cat['institutions']:
        progs = [{k: v for k, v in p.items() if k not in ('institutionId', 'subjects', 'sourceDoc')} for p in i['programmes']]
        insts.append({k: (progs if k == 'programmes' else v) for k, v in i.items()})  # keeps the original key order
    digest = hashlib.sha256(json.dumps(cat['institutions'], sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode('utf-8')).hexdigest()[:12]
    out = {'schemaVersion': cat['schemaVersion'], 'build': digest, 'note': cat['note'], 'institutions': insts, 'subjectCodes': SUBJECT_CODES}
    text = HEADER + 'window.MZ_CATALOGUE = ' + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ';\n'
    return cat, digest, text


def main(argv):
    cat, digest, text = build()
    cur = C.read_text(OUT) if os.path.exists(OUT) else ''
    if '--check' in argv:
        stale = cur != text or cat.get('build') != digest
        if stale:
            C.log('catalogue_data.js / build id is out of date: run python scripts/build_catalogue.py')
        return 1 if stale else 0
    if cat.get('build') != digest:
        cat['build'] = digest
        C.save(C.path('catalogue.json'), cat)
    if cur != text:
        with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        C.log('rebuilt js/catalogue_data.js (build %s)' % digest)
    else:
        C.log('catalogue already up to date (build %s)' % digest)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
