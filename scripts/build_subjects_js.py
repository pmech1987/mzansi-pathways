#!/usr/bin/env python3
"""Writes js/subjects_data.js from SUBJECTS in scripts/pipeline_extract.py so the browser tool and the pipeline can never drift apart.
    python scripts/build_subjects_js.py           # rebuild
    python scripts/build_subjects_js.py --check   # exit 1 if out of date"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mz_common as C
import pipeline_extract as X
OUT = os.path.join(C.ROOT, 'js', 'subjects_data.js')


def text():
    return '/* Generated by scripts/build_subjects_js.py from pipeline_extract.SUBJECTS - do not edit by hand. */\nwindow.MZ_SUBJECTS = ' + json.dumps([[rx, names] for _, rx, names in X.SUBJECTS], separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    t, cur = text(), (C.read_text(OUT) if os.path.exists(OUT) else '')
    if '--check' in sys.argv: sys.exit(0 if t == cur else 1)
    if t != cur: C.write_atomic(OUT, t)
    C.log('js/subjects_data.js up to date')
